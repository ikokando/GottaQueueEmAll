param(
    [string]$ClientId = $env:BLIZZARD_CLIENT_ID,
    [string]$ClientSecret = $env:BLIZZARD_CLIENT_SECRET,
    [string]$Out = (Join-Path (Split-Path $PSScriptRoot) "UI\Realms.lua"),
    [string[]]$Regions = @("us", "eu", "kr", "tw")
)
# Realm -> country for UI/Region.lua, from Blizzard's Game Data API (realm search):
#   powershell -File tools\MakeRealms.ps1 -ClientId <id> -ClientSecret <secret>
# or with BLIZZARD_CLIENT_ID / BLIZZARD_CLIENT_SECRET set. A free API client:
# https://develop.battle.net/access/clients. The credentials are only sent to
# Blizzard; UI\Realms.lua gets the realm list, nothing else.
# Country: EU by the realm's language (English realms: "EU"); US by language
# (ptBR: Brazil, esMX: Latin America) and time zone (Australia/*: Oceania).
$ErrorActionPreference = "Stop"
if (-not $ClientId -or -not $ClientSecret) { Write-Error "Client ID and secret needed (see the top of this script)."; exit 2 }
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$basic = [Convert]::ToBase64String([Text.Encoding]::ASCII.GetBytes("${ClientId}:${ClientSecret}"))
$token = (Invoke-RestMethod -Method Post -Uri "https://oauth.battle.net/token" `
    -Headers @{ Authorization = "Basic $basic" } -Body @{ grant_type = "client_credentials" }).access_token
$auth = @{ Authorization = "Bearer $token" }

# Read as UTF-8 whatever the response says (realm names: Português, Cyrillic, ...).
function Get-Json($url) {
    $resp = Invoke-WebRequest -UseBasicParsing -Uri $url -Headers $auth
    return [Text.Encoding]::UTF8.GetString($resp.RawContentStream.ToArray()) | ConvertFrom-Json
}

# The same key UI/Region.lua makes of a realm: without spaces, hyphens,
# apostrophes, dots and brackets, A-Z in lower case (Lua's lower stops there).
function Get-Key($name) {
    $k = $name -replace "[\s\-'\.\(\)]", ""
    return [regex]::Replace($k, "[A-Z]", { param($m) $m.Value.ToLowerInvariant() })
}

function Get-Country($region, $locale, $tz) {
    $locale = "$locale" -replace "_", ""
    if ($region -eq "eu") {
        $byLang = @{ deDE = "DE"; frFR = "FR"; esES = "ES"; itIT = "IT"; ruRU = "RU"; ptPT = "PT" }
        if ($byLang.ContainsKey($locale)) { return $byLang[$locale] }
        return "EU"
    }
    if ($region -eq "us") {
        if ($locale -eq "ptBR") { return "BR" }
        if ($locale -eq "esMX") { return "MX" }
        if ("$tz" -like "Australia/*") { return "AU" }
        return "US"
    }
    return $region.ToUpperInvariant()   # kr, tw
}

function Lua-String($s) { return '"' + ($s -replace '\\', '\\' -replace '"', '\"') + '"' }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("-- Generated by tools/MakeRealms.ps1 from Blizzard's realm list ($(Get-Date -Format yyyy-MM-dd)). Don't edit by hand.")
$lines.Add("-- Realm key (no spaces, hyphens, apostrophes, dots or brackets; A-Z in lower case) = { country, name }.")
$lines.Add("local _, ns = ...")
$lines.Add("ns.Realms = {")
foreach ($region in $Regions) {
    $map = New-Object 'System.Collections.Generic.SortedDictionary[string,string[]]' ([StringComparer]::Ordinal)
    $page = 1
    do {
        $url = "https://$region.api.blizzard.com/data/wow/search/realm?namespace=dynamic-$region&orderby=id&_pageSize=250&_page=$page"
        $res = Get-Json $url
        foreach ($item in $res.results) {
            $d = $item.data
            if ($d.is_tournament) { continue }
            $country = Get-Country $region $d.locale $d.timezone
            # Every localized name: the client shows its own language's.
            $names = @()
            if ($d.name -is [string]) { $names = @($d.name) }
            else { $names = @($d.name.PSObject.Properties | ForEach-Object { $_.Value } | Where-Object { $_ }) }
            foreach ($n in ($names | Select-Object -Unique)) {
                $k = Get-Key $n
                if ($k -and -not $map.ContainsKey($k)) { $map[$k] = @($country, $n) }
            }
        }
        $page++
    } while ($page -le $res.pageCount)

    $lines.Add("    $($region.ToUpperInvariant()) = {")
    foreach ($kv in $map.GetEnumerator()) {
        $lines.Add("        [$(Lua-String $kv.Key)] = { `"$($kv.Value[0])`", $(Lua-String $kv.Value[1]) },")
    }
    $lines.Add("    },")
    $counts = $map.Values | Group-Object { $_[0] } | Sort-Object Name | ForEach-Object { "$($_.Name) $($_.Count)" }
    "{0}: {1} names ({2})" -f $region, $map.Count, ($counts -join ", ")
}
$lines.Add("}")
[IO.File]::WriteAllText($Out, ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding($false)))
"written: $Out"
